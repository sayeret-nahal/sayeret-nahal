// `npm run local` — the whole system on this computer, no cloud and no Docker:
// PostgreSQL 17 (embedded) → PostgREST → local auth gateway → Next.js.
// Options: --fresh (wipe local data and start over), --prod (build + `next start` instead of dev).
import { spawn } from "node:child_process";
import { existsSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { LOCAL, PG_PORT, ROOT, connString, localSecrets, seedDemo, startDb } from "./db.mjs";
import { GATEWAY_PORT, REST_PORT, anonKey, startGateway } from "./gateway.mjs";

const args = new Set(process.argv.slice(2));
const APP_PORT = Number(process.env.PORT ?? 3000);
const POSTGREST_BIN = process.env.POSTGREST_BIN ?? join(ROOT, "..", ".tools", "postgrest", "postgrest");
const children = [];
// child tools (Turbopack's loader workers, npm scripts) must find the same node binary
const childEnv = {
  ...process.env,
  PATH: [dirname(process.execPath), process.env.PATH].filter(Boolean).join(":"),
  LOCAL_DEMO_LOGIN: "1", // one-click demo login — only in this local environment
};

function log(msg) { console.log(msg); }

async function waitFor(url, name, tries = 60) {
  for (let i = 0; i < tries; i++) {
    try { await fetch(url); return; } catch { await new Promise((r) => setTimeout(r, 500)); }
  }
  throw new Error(`${name} did not start`);
}

/** Rebuild only when the code changed since the last build (keeps restarts fast). */
function needsBuild() {
  const id = join(ROOT, ".next", "BUILD_ID");
  if (!existsSync(id)) return true;
  const built = statSync(id).mtimeMs;
  const newest = (dir) => readdirSync(dir, { withFileTypes: true }).reduce((m, d) => {
    const f = join(dir, d.name);
    return Math.max(m, d.isDirectory() ? newest(f) : statSync(f).mtimeMs);
  }, 0);
  return Math.max(newest(join(ROOT, "src")), statSync(join(ROOT, "next.config.ts")).mtimeMs, statSync(join(ROOT, "package.json")).mtimeMs) > built;
}

async function main() {
  if (!existsSync(POSTGREST_BIN)) {
    console.error(`\nחסר PostgREST (שכבת ה-API של Supabase). התקינו אותו פעם אחת:
  macOS:  brew install postgrest      ואז:  POSTGREST_BIN=$(which postgrest) npm run local
  או הורידו את הגרסה ל-macOS מ-https://github.com/PostgREST/postgrest/releases ושמרו כ-${POSTGREST_BIN}\n`);
    process.exit(1);
  }
  if (args.has("--fresh")) rmSync(join(LOCAL, "pgdata"), { recursive: true, force: true });

  log("מפעיל מסד נתונים מקומי…");
  const db = await startDb({ log });
  await seedDemo(log);

  const { jwtSecret, authenticatorPassword } = localSecrets();
  const conf = join(LOCAL, "postgrest.conf");
  writeFileSync(conf, [
    `db-uri = "${connString("authenticator", authenticatorPassword)}"`,
    `db-schemas = "public"`,
    `db-anon-role = "anon"`,
    `db-extra-search-path = "public, extensions"`,
    `jwt-secret = "${jwtSecret}"`,
    `server-host = "127.0.0.1"`,
    `server-port = ${REST_PORT}`,
    `db-pool = 10`,
    `log-level = "warn"`,
  ].join("\n"), { mode: 0o600 });
  log("מפעיל PostgREST…");
  // the macOS PostgREST build links libpq dynamically; reuse the one shipped with embedded-postgres
  const pgLib = join(ROOT, "node_modules", "@embedded-postgres", "darwin-arm64", "native", "lib");
  children.push(spawn(POSTGREST_BIN, [conf], {
    stdio: ["ignore", "inherit", "inherit"],
    env: { ...process.env, DYLD_FALLBACK_LIBRARY_PATH: [pgLib, process.env.DYLD_FALLBACK_LIBRARY_PATH].filter(Boolean).join(":") },
  }));
  await waitFor(`http://127.0.0.1:${REST_PORT}/`, "PostgREST");

  await startGateway();
  const key = await anonKey();
  writeFileSync(join(ROOT, ".env.local"), [
    "# generated by scripts/local/start.mjs — local environment only",
    `NEXT_PUBLIC_SUPABASE_URL=http://127.0.0.1:${GATEWAY_PORT}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${key}`,
    `NEXT_PUBLIC_APP_URL=http://localhost:${APP_PORT}`,
    `INGEST_SECRET=${localSecrets().ingestSecret}`,
    `HOOK_KEY=${localSecrets().hookKey}`,
    `CRON_SECRET=${localSecrets().cronSecret}`,
    "",
  ].join("\n"));

  const next = join(ROOT, "node_modules", "next", "dist", "bin", "next");
  if (args.has("--prod") && needsBuild()) {
    log("בונה גרסת ייצור…");
    await new Promise((ok, bad) => spawn(process.execPath, [next, "build"], { cwd: ROOT, stdio: "inherit", env: childEnv }).on("exit", (c) => (c === 0 ? ok() : bad(new Error("build failed")))));
  }
  children.push(spawn(process.execPath, [next, args.has("--prod") ? "start" : "dev", "-p", String(APP_PORT)], { cwd: ROOT, stdio: "inherit", env: childEnv }));

  log(`\nהמערכת עולה בכתובת http://localhost:${APP_PORT}
חשבונות בדיקה (אחד לכל תפקיד) וסיסמאות: ${join(LOCAL, "test-accounts.txt")}
טפסים ציבוריים: /talk  /concern
עצירה: Ctrl+C\n`);

  const stop = async () => {
    for (const c of children) c.kill("SIGTERM");
    await db.stop().catch(() => {});
    process.exit(0);
  };
  process.on("SIGINT", stop);
  process.on("SIGTERM", stop);
  void PG_PORT;
}

main().catch((e) => {
  console.error(e);
  for (const c of children) c.kill("SIGTERM");
  process.exit(1);
});
